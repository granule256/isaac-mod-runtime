"""Exercise AddTrinket's production Lua binding through the native-call recorder.

PC resources/scripts/main.lua:853-857 calls the native method with
``addConsumables or addConsumables == nil``. Omission/nil therefore means true,
explicit false stays false, and extra Lua arguments are ignored by the wrapper.
The fake world contains generated bytes only, with no game/mod fixture data.
"""

import subprocess
import tempfile
import unittest
from pathlib import Path

try:
    from .test_support import build_lua_harness
except ImportError:
    from test_support import build_lua_harness

SOURCE = Path(__file__).resolve().parents[1] / "source"

HARNESS = r'''
#include "lua_runtime.hpp"
#include "runtime_constants.hpp"
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

extern "C" {
extern std::uint32_t g_HostEngineCallTrampolineCalls;
extern std::uintptr_t g_HostEngineCallTrampolineLastTarget;
extern std::uint64_t g_HostEngineCallTrampolineLastIntegers[8];
}

template <typename T>
void WriteAt(std::vector<unsigned char>& bytes, std::size_t offset, T value) {
    std::memcpy(bytes.data() + offset, &value, sizeof(value));
}

int main(int argc, char** argv) {
    if (argc != 2) return 90;
    const std::string scenario = argv[1];
    std::string arguments;
    if (scenario == "omitted" || scenario == "noentry") arguments = "1";
    else if (scenario == "nil") arguments = "1, nil";
    else if (scenario == "true") arguments = "1, true";
    else if (scenario == "false") arguments = "1, false";
    else if (scenario == "truthy_zero") arguments = "1, 0";
    else if (scenario == "extra") arguments = "1, false, 'ignored'";
    else if (scenario == "missing") arguments = "";
    else if (scenario == "badid") arguments = "'not an id'";
    else return 91;

    std::vector<unsigned char> module(kGameOwnerGlobalSlotOffset + sizeof(std::uintptr_t));
    std::vector<unsigned char> owner(sizeof(std::uintptr_t));
    std::vector<unsigned char> game(kGamePlayerArrayEndOffset + sizeof(std::uintptr_t));
    std::vector<unsigned char> players(sizeof(std::uintptr_t));
    std::vector<unsigned char> player(kEntityPlayerSize);
    const auto base = reinterpret_cast<std::uintptr_t>(module.data());
    const auto receiver = reinterpret_cast<std::uintptr_t>(player.data());
    static_assert(kEntityPlayerAddTrinketOffset < kGameOwnerGlobalSlotOffset);
    if (scenario != "noentry") {
        WriteAt(module, kEntityPlayerAddTrinketOffset, kEntityPlayerAddTrinketEntryWord);
    }
    WriteAt(module, kGameOwnerGlobalSlotOffset, reinterpret_cast<std::uintptr_t>(owner.data()));
    WriteAt(owner, 0, reinterpret_cast<std::uintptr_t>(game.data()));
    WriteAt(players, 0, receiver);
    WriteAt(game, kGamePlayerArrayBeginOffset, reinterpret_cast<std::uintptr_t>(players.data()));
    WriteAt(game, kGamePlayerArrayEndOffset,
            reinterpret_cast<std::uintptr_t>(players.data()) + sizeof(std::uintptr_t));
    WriteAt(player, 0, base + kEntityPlayerVtableOffset);
    WriteAt(player, kEntityTypeOffset, kEntityTypePlayer);
    LuaRuntime::SetEngineModuleBase(base);

    const std::string script =
        "local p = Isaac.GetPlayer(0)\n"
        "local ok, result = pcall(function() return p:AddTrinket(" + arguments + ") end)\n"
        "print('TRINKET ok=' .. tostring(ok))\n"
        "print('TRINKET result=' .. tostring(result))\n";
    LuaRuntime::InitializeFromBuffer(script.data(), script.size(), "@add-trinket-defaults.lua");
    std::printf("TRINKET calls=%u\n", g_HostEngineCallTrampolineCalls);
    std::printf("TRINKET target_ok=%d\n",
                g_HostEngineCallTrampolineLastTarget == base + kEntityPlayerAddTrinketOffset);
    std::printf("TRINKET receiver_ok=%d\n",
                g_HostEngineCallTrampolineLastIntegers[0] == receiver);
    std::printf("TRINKET id=%llu\n",
                static_cast<unsigned long long>(g_HostEngineCallTrampolineLastIntegers[1]));
    std::printf("TRINKET first_pickup=%llu\n",
                static_cast<unsigned long long>(g_HostEngineCallTrampolineLastIntegers[2]));
    return 0;
}
'''


class AddTrinketDefaultTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temporary = tempfile.TemporaryDirectory(prefix="isaac-add-trinket-")
        cls.binary = build_lua_harness(
            source_root=SOURCE,
            workdir=Path(cls.temporary.name) / "harness",
            harness_source=HARNESS,
        )

    @classmethod
    def tearDownClass(cls):
        cls.temporary.cleanup()

    def run_scenario(self, scenario):
        result = subprocess.run([str(self.binary), scenario], text=True, capture_output=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        return result.stdout + result.stderr

    def assert_native_call(self, scenario, first_pickup):
        out = self.run_scenario(scenario)
        for line in ("ok=true", "result=nil", "calls=1", "target_ok=1", "receiver_ok=1", "id=1",
                     f"first_pickup={first_pickup}"):
            self.assertIn("TRINKET " + line + "\n", out, out)

    def test_omitted_second_argument_defaults_to_true(self):
        self.assert_native_call("omitted", 1)

    def test_nil_second_argument_defaults_to_true(self):
        self.assert_native_call("nil", 1)

    def test_explicit_booleans_reach_native_call(self):
        for scenario, expected in (("true", 1), ("false", 0)):
            with self.subTest(scenario=scenario):
                self.assert_native_call(scenario, expected)

    def test_lua_truthy_zero_remains_true(self):
        self.assert_native_call("truthy_zero", 1)

    def test_extra_arguments_match_pc_wrapper(self):
        self.assert_native_call("extra", 0)

    def test_required_id_is_validated_before_native_call(self):
        for scenario in ("missing", "badid"):
            with self.subTest(scenario=scenario):
                out = self.run_scenario(scenario)
                self.assertIn("TRINKET ok=false\n", out)
                self.assertIn("TRINKET calls=0\n", out)

    def test_entry_word_guard_still_blocks_native_call(self):
        out = self.run_scenario("noentry")
        self.assertIn("TRINKET ok=true\n", out)
        self.assertIn("TRINKET calls=0\n", out)


if __name__ == "__main__":
    unittest.main()

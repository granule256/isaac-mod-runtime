// ============================================================================
// 探针总开关（，2026-09-30 用户指令："现在你将探针都撤去"）
// ============================================================================
//
// **一句话**：正式包（`DIAGNOSTIC_PROBES=0`，默认）里，所有"会做事的"探针采集
// —— 读引擎内存、遍历设备表、查卡上的文件、按次统计 —— 都不再执行；
// 只有专门为诊断构建的包（`DIAGNOSTIC_PROBES=1`）才会打开它们。
//
// 为什么要有这个开关（2026-09-30 的现场）：
//   * 用户报「进游戏开场动画约 10 秒黑屏但有声音」。历史上同一形状（"画面停、音乐继续"）
//     出现过两次（2026-09-24 / 09-25），根因都是**我们模块里的异常展开不了** ⇒ `abort`
//     ⇒ newlib `_exit` 自旋（见 `docs/问题记录-画面卡死-20260924.md`）。那一条已由
//     （展开表登记）修掉；本批要排除的是"**探针本身拖着主线程**"这个可能性。
//   * 探针从起在输入链上越加越多：每帧一次的全动作普查、设备对象整块内存 dump
//     （一次 ~250 格带可读性检查的内存读）、每 API 调用一次的计数。已把"每帧"
//     降成"每 60 帧"，但"每 60 帧"在加载/播片期间照样会撞上主线程。
//   * ⇒ 与其继续调频，不如**让正式包根本没有这套东西**：诊断能力靠"探针构建"按需拿回来。
//
// 口径（**哪些关、哪些不关** —— 这不是"随手一关"，判据在下面）：
//
//   关（`EXL_DIAGNOSTIC_PROBES` 保护的，全是**纯观测**）：
//     * 只写、运行时**没有任何代码读**的 `g_*` 诊断量的**采集动作**；
//     * 判据来源：`grep` 全仓，这些量的读取点只有"读数工具"（宿主侧按符号直读），
//       运行时侧一个都没有 ⇒ 关掉它们**不改变任何行为**。
//
//   不关（**承重的，关掉会改行为甚至崩**）：
//     * `g_DefaultManifestState`、`CardSwitchOn()` 依赖的 `g_CardSwitchMask`、
//       `g_IsaacEngineRowRejectGuard`、`g_TouchPointerInitState`、模组页的 `g_ModRow*` 等
//       —— 它们**被运行时读**，是状态机/保险/门控，不是探针；
//     * 纯 `fetch_add` 的**计数**（每帧几十次原子加，代价在噪声级）**保留**：
//       关掉它们对卡顿没有可测影响，却会让读数工具整体失明 —— 那是把"下次出问题时的
//       唯一手段"也一起扔掉。
//     * 只在**出错时**才走一次的量（`RecordLuaErrorHistory` / `RecordRequireFailure`）保留：
//       没有每帧代价，而它们是定位"某个模组整体不生效"的第一手段。
//
// 怎么用：
//   * 正式包：什么都不用传（默认 0）。
//   * 探针包：`make ... DIAGNOSTIC_PROBES=1`（与 `PROBE_BREAK=1` 等一起用）。
//
// 只改 `runtime/Makefile` 与各探针函数的函数体，没有改任何 `g_*` 的声明：
//   声明留着 ⇒ 读数工具仍能按符号解析（值恒 0），也不会动 `bss` 布局。
//   （这批刻意不删声明：删了要同步改读数工具的 171 条读取规格与一批门禁，属于单独一批的事。）

#if !defined(EXL_DIAGNOSTIC_PROBES)
#define EXL_DIAGNOSTIC_PROBES 0
#endif

#if (EXL_DIAGNOSTIC_PROBES != 0) && (EXL_DIAGNOSTIC_PROBES != 1)
#error EXL_DIAGNOSTIC_PROBES must be 0 or 1
#endif

// GPU尚未完成则不能卸载或归还；原生FreeGraphicsMemory只排队，最后一步才真正归还。
template<class Operations>
bool ReclaimModReloadGraphics(Operations& operations) noexcept {
    if (!operations.WaitForGpu()) return false;
    operations.ReleaseLanguageFonts();
    return operations.ReclaimDeferred();
}

// 原生UnloadMods 0x41F5F8..0x41F628：list头+F0、begin+F8、size+100，
// 节点next+8、数据指针+10，Manager::FreeImage 接SmartPointer+278。
// 先只读预检完整链，再释放。计数约束同时挡住循环链和半截链，不分配临时指针数组。
template<class Read, class Release>
bool VisitModEntryImages(std::uintptr_t entry, Read read, Release release, bool destroy) noexcept {
    constexpr auto maximum = std::numeric_limits<std::uintptr_t>::max();
    if (!entry || entry > maximum - 0x100) return false;
    std::uintptr_t count{}, node{};
    if (!read(entry+0x100,&count) || count > 65536 || !read(entry+0xf8,&node)) return false;
    const auto head = entry+0xf0;
    for (std::uintptr_t i=0; i<count; ++i) {
        if (!node || node==head || node > maximum-0x10) return false;
        std::uintptr_t value{}, next{};
        if (!read(node+0x10,&value) || !value || value > maximum-0x280 ||
            !read(node+8,&next)) return false;
        if (destroy) release(value+0x278);
        node = next;
    }
    return node==head;
}

// 原生清理仍复用默认ANM2/shader的释放，但绝不让它delete菜单静态条目或内容竞技场。
template<class ReadVector, class WriteVector, class Unload>
bool WithEmptyModVector(ReadVector read, WriteVector write, Unload unload) noexcept {
    std::array<std::uintptr_t,3> saved{};
    if (!read(&saved) || !write(std::array<std::uintptr_t,3>{})) return false;
    unload();
    return write(saved);
}

#pragma once

// ============================================================================
// 通用引擎调用跳板
// ============================================================================
//
// **它解决什么问题**：数据行机制（`engine_method_api.hpp`）的下一步是"**任意签名**的引擎方法
// 都只花一行数据"。在它之前，一条 API 能不能走数据行取决于共享处理器里**写死了几种 C++ 签名**
// （`void(*)(this)`、`void(*)(this,i32)`…）—— 换一个参数表就得再加一个 `case`，也就是**又要写代码**。
//
// 这个跳板把"装参数 + 调进去"从**编译期签名**变成**运行期数据**：
//
//   1. 调用方把接收者与各参数按种类分别填进两个数组
//      （整数/指针/布尔 → `integerArguments`；浮点 → `floatArguments`）；
//   2. 跳板按 AAPCS64 把它们装进 `x0..x7` 与 `d0..d7`，`blr` 到目标函数；
//   3. 回来后把返回值原样回填（`x0` 与 `d0` 各一个格子），由调用方按返回种类解释。
//
// 于是"新增一条引擎方法 API" = **一行 16 字节数据 + （签名组合首次出现时）一行 16 字节描述符**，
// **0 字节代码** —— 除非需要一种全新的**参数/返回种类**（例如字符串参数、16 字节结构体返回），
// 那才是真正的一次性成本。
//
// **能力边界（写清楚，免得被当成万能）**：
//   * 参数上限：8 个整数类（含指针/布尔）+ 8 个浮点类 —— 覆盖引擎里我们见过的所有方法；
//   * 返回：只支持**标量**（`void` / 整数 / 指针 / 浮点，即 `x0` 或 `d0`）。
//     返回**结构体**（16 字节的 `Vector`/`KColor` 一类，走 `x8` 间接结果寄存器）**不在**本机制内，
//     那类成员继续手写（或者将来再加一个"带结果缓冲区"的跳板）。
//   * 不处理变参、不处理返回 `float` 与 `double` 之间的区别（AAPCS64 里两者都在 `d` 寄存器，
//     由**调用方按数据行里的返回种类**解释 —— 读 `d0` 的低 32 位还是全 64 位）。
//     2026-10-04把这条契约写死（此前只是"提了一句"，实现侧理解错了）：
//     引擎里那些形参的 mangled 末位是 **`f` = `float`** ⇒ 按 AAPCS64，`float` 占 `sN`
//     = `dN` 的**低 32 位**。⇒ **`floatArguments[i]` 的低 32 位必须是 f32 位型、高 32 位填 0**，
//     **不是**"把 Lua 数值 `static_cast<double>` 之后原样放进去"（那样低 32 位是 double 的低半，
//     引擎读到的通常就是 `0.0f`）。返回值同理：引擎在 `s0` 回 `float` ⇒ 我们读 `d0` 的
//     **低 32 位**再按 `float` 解释。
//     ⇒ 两侧各有一个转换助手（`EngineFloatArgument` / `EngineFloatResult`，都在 `isaac_api.cpp`
//     的共享处理器旁边），**别在别处再写一份**。

#include <cstdint>

extern "C" {

// 按 AAPCS64 调一个引擎函数：`x0` = `function`，`x1` = 整数/指针参数数组，
// `x2` = 浮点参数数组，`x3` = 整数返回值回填处，`x4` = 浮点返回值回填处。
//
// 两个数组都必须至少有 8 个元素（跳板无条件读满 8 个 `x` 与 8 个 `d`）—— 调用方
// 用零填满即可；参数用不到的格子填什么都不影响（引擎不会读超出其签名的那几个寄存器）。
//
// 两个回填指针都必须非空（返回 `void` 时写进去的值没有意义，但指针仍然要合法）。
void EngineCallTrampoline(std::uintptr_t function,
                          const std::uint64_t* integerArguments,
                          const double* floatArguments,
                          std::uint64_t* integerResult,
                          double* floatResult) noexcept;

} // extern "C"

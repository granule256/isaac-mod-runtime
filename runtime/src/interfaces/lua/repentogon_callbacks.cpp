// A bounded read-only ID map addresses the cached states, not the ordinary ID array.
constexpr auto MakeStateIndices() noexcept {
    std::array<std::uint8_t,1485-1000> indices{};
    for(auto& index:indices)index=255;
    for(std::size_t i=0;i<kCallbackCount;++i)indices[kCallbacks[i].id-1000]=static_cast<std::uint8_t>(i);
    return indices;
}
constexpr auto kStateIndices=MakeStateIndices();
std::array<ExtendedCallbackState*,kCallbackCount> g_States{};
void Reset() noexcept {
    g_States.fill(nullptr);
    ResetRepentogonTimerApi();
    ResetRepentogonGameStateData();
    ResetRepentogonAchievementState();
    ResetRepentogonCustomCompletionMarks();
    ClearRepentogonMenuInputMask();
    if(g_NativePort&&g_NativePort->resetCustomCacheRun)g_NativePort->resetCustomCacheRun();
}

bool Ready() noexcept {
    return g_NativePort&&g_NativePort->ready&&g_NativePort->install&&g_NativePort->ready();
}
int Initialize(lua_State* state) {
    for(std::size_t i=0;i<g_States.size();++i) {
        g_States[i]=FindExtendedCallback(kCallbacks[i].id);
        if(!g_States[i])return luaL_error(state,"REPENTOGON callback state unavailable");
    }
    if(!g_NativePort||!g_NativePort->install||!g_NativePort->install())
        return luaL_error(state,"REPENTOGON callback hooks unavailable");
    RegisterProceduralItemApi(state);
    RegisterPlayerManagerApi(state);
    RegisterRepentogonEntityConfigViews(state);
    RegisterRepentogonSpriteViews(state);
    RegisterRepentogonMenuWorldApi(state);
    RegisterRepentogonColorModifierApi(state);
    RegisterRepentogonCharacterMenuApi(state);
    RegisterRepentogonItemOverlayApi(state);
    RegisterRepentogonRemainingBulkViews(state);
    RegisterRepentogonSaveStateViews(state);
    RegisterRepentogonBocViews(state);
    static_cast<void>(RegisterRepentogonConsoleApi(state));
    static_cast<void>(RegisterRepentogonTimerApi(state));
    static_cast<void>(RegisterRepentogonRoomConfigApi(state));
    static_cast<void>(RegisterRepentogonXmlDataApi(state));
    static_cast<void>(RegisterRepentogonGameStateData(state));
    static_cast<void>(RegisterRepentogonRoomPlacementApi(state));
    RegisterRepentogonGeneratorViews(state);
    static_cast<void>(RegisterRepentogonImGuiApi(state));
    RegisterRepentogonWeaponApi(state);
    RegisterRepentogonMinimapApi(state);
    RegisterRepentogonPlayerHudHearts(state);
    static_cast<void>(RegisterCustomCacheApi(state));
    return 0;
}
